def main() -> None:
    live = live_slugs()
    held = held_slugs()
    blocked = live | held
    live_tok = {s: toks(s) for s in live}

    rows = from_plan50() + extra_topics()
    seen = set()
    kept = []
    dropped = []
    for a in rows:
        slug = a['slug']
        if slug in seen:
            dropped.append((slug, 'dup-in-plan'))
            continue
        if slug in blocked:
            dropped.append((slug, 'live-or-held'))
            continue
        st = toks(slug)
        hit = None
        best = 0.0
        for ls, lt in live_tok.items():
            j = jaccard(st, lt)
            if j > best:
                best, hit = j, ls
        if best >= 0.55:
            dropped.append((slug, f'jaccard {best:.2f} vs {hit}'))
            continue
        seen.add(slug)
        kept.append(a)

    # If short of 250, we fail loudly so a human adds more unique intents.
    if len(kept) > 250:
        kept.sort(key=lambda a: (a['priority'], a['slug']))
        extra = kept[250:]
        kept = kept[:250]
        print('trimmed to 250, removed', [a['slug'] for a in extra])
    payload = {
        'generated': '2026-08-28',
        'count': len(kept),
        'target': 250,
        'method': (
            'plan-50 (51 collision-cleared intents from 2026-08-27) plus catalog-bot jobs, '
            'integrations with a unique never-line, hedged comparisons, leftover plan-100-v2 ops, '
            'and migrations. Live corpus slugs and held-duplicates are blocked. Slug-token Jaccard '
            '>= 0.55 against a live slug is dropped. Rakazo is excluded until VERIFIED-FACTS covers it. '
            'Product facts only from docs/seo/VERIFIED-FACTS-2026-08-25.md. LONGFORM-SPEC and HUMANIZE-SPEC.'
        ),
        'note': (
            'Grok Bot long-tail plan. Skip any slug that later appears in packages/web/src/app/blog/posts. '
            'Do not write a page that remakes a live twin named in distinct_from. Third-party products are '
            'hedged to the vendor page. Never invent allowance dollars, SuperGrok Heavy $300, or a Linux app.'
        ),
        'live_corpus_at_plan': len(live),
        'dropped': [{'slug': s, 'reason': r} for s, r in dropped],
        'articles': kept,
    }
    OUT.write_text(json.dumps(payload, indent=1) + '\n')
    print(f'wrote {OUT} count={len(kept)} dropped={len(dropped)} live={len(live)}')
    if len(kept) < 250:
        print('SHORT: need', 250 - len(kept), 'more unique intents')
    elif len(kept) > 250:
        print('LONG: trim', len(kept) - 250)
    by = {}
    for a in kept:
        by[a['cluster']] = by.get(a['cluster'], 0) + 1
    print('clusters', dict(sorted(by.items(), key=lambda kv: -kv[1])))
    if dropped:
        print('dropped sample:')
        for s, r in dropped[:15]:
            print(f'  {s}: {r}')


if __name__ == '__main__':
    main()
