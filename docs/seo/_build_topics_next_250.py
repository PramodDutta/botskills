"""Build docs/seo/topics-next-250.json: 250 net-new intents vs the live corpus.

Rejects any slug that already exists as a post file, a held-duplicate, or a
plan-50 slug collision with live. Token-overlap against live slugs is flagged
and dropped above a Jaccard of 0.55.
"""
from __future__ import annotations

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
POSTS = ROOT / 'packages/web/src/app/blog/posts'
HELD = ROOT / 'docs/seo/held-duplicates'
OUT = ROOT / 'docs/seo/topics-next-250.json'
PLAN50 = ROOT / 'docs/seo/plan-50-2026-08-27.json'
BOTS = ROOT / 'seed-bots'

STOP = {
    'the', 'a', 'an', 'and', 'or', 'for', 'to', 'of', 'in', 'with', 'that', 'your',
    'you', 'how', 'what', 'grok', 'bot', 'bots', 'is', 'it', 'can', 'do', 'does',
    'not', 'on', 'as', 'are', 'be', 'without', 'from', 'who', 'which', 'a', 'vs',
}


def toks(s: str) -> set[str]:
    return {w for w in re.sub(r'[^a-z0-9 ]', ' ', s.lower()).split() if len(w) > 2 and w not in STOP}


def jaccard(a: set[str], b: set[str]) -> float:
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


def live_slugs() -> set[str]:
    return {p.stem for p in POSTS.glob('*.ts') if p.stem != 'index'}


def held_slugs() -> set[str]:
    return {p.stem for p in HELD.glob('*.ts')}


def article(slug, title, keyword, category, cluster, priority, why_new, distinct_from=''):
    return {
        'slug': slug,
        'title': title,
        'keyword': keyword,
        'category': category,
        'cluster': cluster,
        'priority': priority,
        'status': 'planned',
        'why_new': why_new,
        'distinct_from': distinct_from,
    }


def from_plan50() -> list[dict]:
    raw = json.loads(PLAN50.read_text())
    out = []
    for a in raw['articles']:
        slug = a['slug']
        title = a['title']
        track = a.get('track', 'ops')
        cat = a.get('category', 'Guide')
        cluster = {
            'problem-intent': 'problem',
            'orphan-bot': 'jobs',
            'ops-gap': 'ops',
            'decision': 'decision',
            'migration': 'migration',
        }.get(track, track)
        kw = slug.replace('-', ' ').replace('grok bot', 'grok bot')
        why = a.get('why_new') or a.get('bot') or track
        bot = a.get('bot')
        if bot:
            why = f"Catalog bot {bot}: {why if isinstance(why, str) else 'no dedicated article yet.'}"
        pri = 1 if track in ('problem-intent', 'migration') else 2
        out.append(article(slug, title, kw[:80], cat, cluster, pri, str(why)))
    return out


